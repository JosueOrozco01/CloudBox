/*
 * CloudBox - Modelo Compartir
 *
 * Representa una acción mediante la cual un usuario comparte
 * un archivo o carpeta con otro usuario.
 *
 * Conceptos:
 *
 * EMISOR:
 * Usuario que comparte el archivo o carpeta.
 *
 * RECEPTOR:
 * Usuario que recibe el acceso.
 *
 * RECURSO:
 * Archivo o carpeta que se está compartiendo.
 *
 * PERMISOS:
 * Define qué puede hacer el receptor con el recurso.
 *
 * Ejemplos:
 * - Ver.
 * - Descargar.
 * - Editar.
 *
 * Este modelo debe respetar las relaciones definidas
 * en la base de datos.
 */