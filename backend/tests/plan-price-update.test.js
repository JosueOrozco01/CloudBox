'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');

const updateSql = fs.readFileSync(path.join(__dirname, '../../supabase/manual/commercial/20261112_plan_price_updates.sql'), 'utf8');
const stage2Sql = fs.readFileSync(path.join(__dirname, '../../supabase/manual/commercial/20261027_etapa2.sql'), 'utf8');
const changeFunctionStart = stage2Sql.indexOf('CREATE OR REPLACE FUNCTION public.cloudbox_subscription_change_v1(');
const changeFunctionEnd = stage2Sql.indexOf('$function$;', changeFunctionStart) + '$function$;'.length;
const baselineChangeFunction = stage2Sql.slice(changeFunctionStart, changeFunctionEnd);

test('manual price update changes existing prices and preserves Free, subscriptions, payments, and receipts', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE TABLE public.estado_plan(id integer PRIMARY KEY,nombre text NOT NULL);
      CREATE TABLE public.plan(id integer PRIMARY KEY,nombre text NOT NULL,descripcion text,precio numeric NOT NULL,
        espacio_maximo_gb numeric NOT NULL,vigencia_dias integer NOT NULL,id_estado integer NOT NULL);
      CREATE TABLE public.usuario(id integer PRIMARY KEY);
      CREATE TABLE public.estado_suscripcion(id integer PRIMARY KEY,nombre text NOT NULL);
      CREATE TABLE public.estado_pago(id integer PRIMARY KEY,nombre text NOT NULL);
      CREATE TABLE public.metodo_pago(id integer PRIMARY KEY,estado boolean NOT NULL);
      CREATE TABLE public.suscripcion(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,fecha_inicio date NOT NULL,
        fecha_fin date NOT NULL,id_usuario integer NOT NULL,id_plan integer NOT NULL,id_estado integer NOT NULL,
        FOREIGN KEY(id_plan) REFERENCES public.plan(id));
      CREATE TABLE public.credito_suscripcion(id_usuario integer PRIMARY KEY,saldo numeric NOT NULL DEFAULT 0,fecha_actualizacion timestamptz NOT NULL DEFAULT now());
      CREATE TABLE public.evento_credito_suscripcion(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_usuario integer NOT NULL,
        id_suscripcion_anterior integer,id_suscripcion_nueva integer,monto_generado numeric NOT NULL DEFAULT 0,
        monto_aplicado numeric NOT NULL DEFAULT 0,saldo_resultante numeric NOT NULL DEFAULT 0,referencia text);
      CREATE TABLE public.programacion_suscripcion(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_usuario integer NOT NULL,
        id_suscripcion_origen integer NOT NULL,id_suscripcion_futura integer,id_pago integer,tipo text NOT NULL,
        id_plan_destino integer NOT NULL,fecha_efectiva date NOT NULL,estado text NOT NULL DEFAULT 'pending');
      CREATE TABLE public.pago(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_usuario integer NOT NULL,
        id_suscripcion integer,id_metodo_pago integer NOT NULL,monto numeric NOT NULL,referencia text,
        transaccion_id text,id_estado integer NOT NULL);
      CREATE TABLE public.comprobante_pago(id integer PRIMARY KEY,id_pago integer,monto numeric NOT NULL);
      INSERT INTO public.estado_plan VALUES(1,'Activo');
      INSERT INTO public.plan VALUES
        (8,'Free',NULL,0,1,36500,1),(1,'Básico',NULL,29,5,30,1),
        (2,'Pro',NULL,89,50,30,1),(3,'Premium',NULL,149,100,30,1);
      INSERT INTO public.usuario VALUES(7),(8);
      INSERT INTO public.estado_suscripcion VALUES(1,'Pendiente'),(2,'Activa'),(3,'PorVencer'),(4,'Vencida'),(5,'Renovada'),(6,'Cancelada');
      INSERT INTO public.estado_pago VALUES(1,'Aprobado'),(2,'Rechazado');
      INSERT INTO public.metodo_pago VALUES(1,true);
      INSERT INTO public.suscripcion(id,fecha_inicio,fecha_fin,id_usuario,id_plan,id_estado)
        VALUES(100,CURRENT_DATE-15,CURRENT_DATE+15,7,1,2),(101,CURRENT_DATE-45,CURRENT_DATE-15,8,2,4);
      INSERT INTO public.pago(id,id_usuario,id_suscripcion,id_metodo_pago,monto,referencia,transaccion_id,id_estado)
        VALUES(200,7,100,1,29,'OLD-BASIC-0001','TRX-OLD-1',1),(201,8,101,1,89,'OLD-PRO-00001','TRX-OLD-2',1);
      INSERT INTO public.comprobante_pago VALUES(300,200,29),(301,201,89);

      CREATE FUNCTION public.cloudbox_stage2_guard_plan() RETURNS trigger
      LANGUAGE plpgsql SET search_path='' AS $old$
      BEGIN
        IF TG_OP='DELETE' THEN
          IF lower(btrim(OLD.nombre))='free' THEN RAISE EXCEPTION 'CLOUDBOX_FREE_PLAN_PROTECTED'; END IF;
          RETURN OLD;
        END IF;
        IF lower(btrim(NEW.nombre))='free' THEN
          IF NEW.precio<>0 OR NEW.espacio_maximo_gb<>1 OR NEW.id_estado<>1 THEN RAISE EXCEPTION 'CLOUDBOX_FREE_PLAN_PROTECTED'; END IF;
        ELSIF NEW.precio=0 THEN RAISE EXCEPTION 'CLOUDBOX_FREE_PLAN_PROTECTED'; END IF;
        IF TG_OP='UPDATE' THEN
          IF lower(btrim(OLD.nombre))='free' AND lower(btrim(NEW.nombre))<>'free' THEN RAISE EXCEPTION 'CLOUDBOX_FREE_PLAN_PROTECTED'; END IF;
          IF (NEW.precio,NEW.espacio_maximo_gb,NEW.vigencia_dias) IS DISTINCT FROM (OLD.precio,OLD.espacio_maximo_gb,OLD.vigencia_dias)
             AND EXISTS(SELECT 1 FROM public.suscripcion WHERE id_plan=OLD.id) THEN RAISE EXCEPTION 'CLOUDBOX_PLAN_TERMS_IMMUTABLE'; END IF;
        END IF;
        RETURN NEW;
      END;
      $old$;
      CREATE FUNCTION public.cloudbox_stage2_lock_plan() RETURNS trigger
      LANGUAGE plpgsql SET search_path='' AS $lock$
      BEGIN
        PERFORM 1 FROM public.plan WHERE id=NEW.id_plan FOR SHARE;
        RETURN NEW;
      END;
      $lock$;
      CREATE TRIGGER cloudbox_stage2_guard_plan BEFORE INSERT OR UPDATE OR DELETE ON public.plan
        FOR EACH ROW EXECUTE FUNCTION public.cloudbox_stage2_guard_plan();
      CREATE TRIGGER cloudbox_stage2_lock_plan BEFORE INSERT OR UPDATE OF id_plan ON public.suscripcion
        FOR EACH ROW EXECUTE FUNCTION public.cloudbox_stage2_lock_plan();
    `);
    assert.ok(changeFunctionStart >= 0 && changeFunctionEnd > changeFunctionStart);
    await db.exec(baselineChangeFunction);

    const oldReceipts = await db.query('SELECT id,id_pago,monto FROM public.comprobante_pago ORDER BY id');
    await db.exec(updateSql);

    const plans = await db.query('SELECT id,nombre,precio,espacio_maximo_gb,vigencia_dias FROM public.plan ORDER BY id');
    assert.deepEqual(plans.rows.map(row => [row.id, row.nombre, Number(row.precio), Number(row.espacio_maximo_gb), row.vigencia_dias]), [
      [1, 'Básico', 9, 5, 30], [2, 'Pro', 25, 50, 30], [3, 'Premium', 39, 100, 30], [8, 'Free', 0, 1, 36500]
    ]);
    const receipts = await db.query('SELECT id,id_pago,monto FROM public.comprobante_pago ORDER BY id');
    assert.deepEqual(receipts.rows, oldReceipts.rows);
    assert.equal((await db.query('SELECT count(*)::int AS count FROM public.plan')).rows[0].count, 4);

    const change = await db.query("SELECT public.cloudbox_subscription_change_v1(7,2,1,'PGLITE-UPGRADE1',false) AS result");
    const result = typeof change.rows[0].result === 'string' ? JSON.parse(change.rows[0].result) : change.rows[0].result;
    assert.equal(Number(result.creditGenerated), 14.5);
    assert.equal(Number(result.amountDue), 10.5);
    assert.equal(Number((await db.query('SELECT monto FROM public.pago WHERE id=200')).rows[0].monto), 29);

    await db.exec('UPDATE public.plan SET precio=11 WHERE id=1');
    await assert.rejects(db.exec('UPDATE public.plan SET espacio_maximo_gb=6 WHERE id=1'), /CLOUDBOX_PLAN_TERMS_IMMUTABLE/);
    await assert.rejects(db.exec("UPDATE public.plan SET nombre='Básico nuevo' WHERE id=1"), /CLOUDBOX_PLAN_NAME_IMMUTABLE/);
    await assert.rejects(db.exec('UPDATE public.plan SET precio=1 WHERE id=8'), /CLOUDBOX_FREE_PLAN_PROTECTED/);
  } finally {
    await db.close();
  }
});
